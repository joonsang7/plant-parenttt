package com.plantparentt.config;

/**
 * @FileName : AppConfig.java
 * @Description : 애플리케이션 설정값을 한 곳에서 관리하는 클래스
 *              네트워크·센서 관련 설정을 변경할 때 이 파일만 수정하면 되도록 하여(SRP 구현하기 위함)
 *              구현 클래스를 열지 않고도 구체적인 설정을 조정 가능하도록 했습니다 (OCP 구현 위함) //OCP란
 */
public class AppConfig {

    // ── 네트워크 설정
    // ────────────────────────────────────────────────────────────────────────────────────────────────────────────────
    /** MQTT 브로커(Mosquitto)가 실행 중인 쪽의 IP 주소를 입력해야만 한다 */
    public static final String BROKER_IP = "172.20.10.10";
    /** MQTT 브로커 포트 */
    public static final int BROKER_PORT = 1883;

    

    // ── 자동 체크 주기
    // ───────────────────────────────────────────────────────────────────────────────────────────────────────────────
    /** Hub 스케줄러가 각 화분을 자동으로 체크하는 주기 (시간) */
    public static final int CHECK_INTERVAL_HOURS = 6;

    

    // ── 건조 판단 기준
    // ───────────────────────────────────────────────────────────────────────────────────────────────────────────────
    /** 관수가 필요한 건조 기준 수분 % (이 값 미만이면 건조로 판단) 
     * 마른 화분의 흙에 직접 토양 수분 센서로 측정해본 결과 8~9%정도의 수분을 가진다는 것을 확인했기에 관수가 필요한 건조 기준을 10%로
     * 설정하고 오차를 5%로 설정함으로써
     * 10% ± 5% (즉 5%~15%) 범위 내에서 안정적으로 유지되는 경우에만 건조로 판단하도록 헀습니다
     */
    public static final int DRY_THRESHOLD = 10;

    /** 안정 판단 허용 오차 (수분 % 기준, 이 범위 내 변동은 안정으로 간주) 
     * "24시간 내내 일정하게 건조한 상태" 인지 확인하는 안전장치 역할을 하는 변수로 VALUE_TOLERANCE를 사용
     * 토양 수분 센서가 완벽하지 않아서 같은 흙에 꽂혀있어도 측정값이 조금씩 튀는데,
     * Tolerance를 사용함으로써 24시간 동안 측정값이 10% ± 5% (즉, 5%~15%) 범위 내에서 일정하게 유지되는 경우에만 건조로
     * 판단하도록 한다
     */
    public static final int VALUE_TOLERANCE = 5;


    /** 건조 상태가 이 시간(시간) 이상 유지되어야 자동 알림 발송 */
    public static final int STABLE_HOURS = 24;


    // ── 관수 감지 기준
    // ─────────────────────────────────────────────────────────────────────────────────────────────────────────────────────────
    /** 건조 알림 후 수분이 이 값(%) 이상으로 회복되면 관수로 자동 감지 */
    public static final int WATERING_DETECTED_THRESHOLD = 50;

    /** 관수 감지 전용 체크 주기 (분). 건조 알림 후 빠르게 관수를 감지하기 위해 짧게 설정 */
    public static final int WATERING_CHECK_INTERVAL_MINUTES = 1;



    // ── 센서 보정 설정
    // ─────────────────────────────────────────────────────────────────────────────────────────────────────────────────────────────
    /** 보정 측정 간격 (밀리초). 5초마다 ADC 값을 읽어 안정 여부를 판단한다. */
    public static final int CALIB_CHECK_INTERVAL_MS = 5_000;

    /** 보정 최소 검사 횟수. 최소 4회(20초) 이상 안정적이어야 보정 완료로 간주한다. */
    public static final int CALIB_MIN_CHECKS = 4;

    /** 보정 최대 검사 횟수. 20회(100초) 이내에 안정되지 않으면 보정 실패(타임아웃). */
    public static final int CALIB_MAX_CHECKS = 100;

    /**
     * 보정 안정 판단 ADC 허용 오차.
     * 최근 CALIB_MIN_CHECKS 개의 ADC 값의 범위(max-min)가 이 값 이하이면 안정으로 판단한다.
     * ADC 전체 범위(0~1023)의 약 5%에 해당한다.
     */
    public static final int CALIB_ADC_TOLERANCE = 50;

    /**
     * 보정값 유효성 판단 비율.
     * 포화 ADC 값이 건조 ADC 값보다 이 비율 이상 높아야 유효한 보정으로 간주한다.
     * (예: 0.5 → wetValue > dryValue * 1.5)
     */
    public static final double CALIB_VALID_RATIO = 0.5;



    // ── 센서 삽입 판단 기준
    // ───────────────────────────────────────────────────────────────────────────────────────────────────────────────────────
    /**
     * 보정 전 센서 삽입 여부를 판단하는 ADC 기준값.
     * latestValue 가 이 값을 초과하면 흙(또는 물)에 꽂혀 있다고 판단한다.
     */
    public static final int SENSOR_INSERT_THRESHOLD = 123;

    private AppConfig() {
    } // 인스턴스 생성 방지를 위한 private 생성자
}
